import { CircleAlert, Eye, EyeOff } from "lucide-react"
import { useActionState, useState } from "react"
import { Link } from "react-router"
import { z } from "zod"
import { BrandMark } from "@/components/brand-mark"
import { Alert, AlertTitle } from "@/components/ui/alert"
import { Button } from "@/components/ui/button"
import { Field, FieldDescription, FieldError, FieldGroup, FieldLabel } from "@/components/ui/field"
import { Input } from "@/components/ui/input"
import { InputGroup, InputGroupAddon, InputGroupButton, InputGroupInput } from "@/components/ui/input-group"
import { Spinner } from "@/components/ui/spinner"
import { ApiError, type FieldErrors, getErrorMessage } from "@/lib/api"
import { MessageBubble } from "@/features/chat/message-bubble"
import { TypingIndicator } from "@/features/chat/typing-indicator"
import { loginSchema, signupSchema } from "./auth-schema"
import { useAuthStore } from "./auth-store"

type AuthMode = "login" | "signup"

const AUTH_COPY = {
  login: {
    title: "Log in to Harbor",
    description: "Pick up your conversations where you left them.",
    submit: "Log in",
    submitting: "Logging in",
    switchPrompt: "New to Harbor?",
    switchLabel: "Create an account",
    switchTo: "/signup",
    passwordAutoComplete: "current-password",
    passwordHint: null,
  },
  signup: {
    title: "Create your account",
    description: "Your conversations are saved so you can come back to them anytime.",
    submit: "Create account",
    submitting: "Creating account",
    switchPrompt: "Already have an account?",
    switchLabel: "Log in",
    switchTo: "/login",
    passwordAutoComplete: "new-password",
    passwordHint: "At least 8 characters.",
  },
} as const

interface AuthFormState {
  email: string
  message: string | null
  fieldErrors: FieldErrors
}

const INITIAL_STATE: AuthFormState = { email: "", message: null, fieldErrors: {} }

const readField = (formData: FormData, name: string): string => {
  const value = formData.get(name)
  return typeof value === "string" ? value : ""
}

const toFieldErrorItems = (messages: string[] | undefined) => messages?.map((message) => ({ message }))

interface AuthPageProps {
  mode: AuthMode
}

export function AuthPage({ mode }: AuthPageProps) {
  return (
    <div className="grid min-h-svh lg:grid-cols-[minmax(0,1fr)_minmax(0,1.1fr)]">
      <AuthShowcase />
      <main className="flex flex-col px-6 py-8 sm:px-10">
        <div className="flex items-center gap-2.5 lg:hidden">
          <BrandMark />
          <span className="text-base font-semibold tracking-tight">Harbor</span>
        </div>
        <div className="flex flex-1 items-center justify-center py-10">
          <AuthForm key={mode} mode={mode} />
        </div>
      </main>
    </div>
  )
}

