function AuthForm({ mode }: AuthPageProps) {
  const copy = AUTH_COPY[mode]
  const login = useAuthStore((state) => state.login)
  const signup = useAuthStore((state) => state.signup)
  const [isPasswordVisible, setIsPasswordVisible] = useState(false)

  const [state, formAction, isPending] = useActionState(
    async (_previous: AuthFormState, formData: FormData): Promise<AuthFormState> => {
      const input = { email: readField(formData, "email"), password: readField(formData, "password") }
      const parsed = (mode === "login" ? loginSchema : signupSchema).safeParse(input)

      if (!parsed.success) {
        return { email: input.email, message: null, fieldErrors: z.flattenError(parsed.error).fieldErrors }
      }

      try {
        await (mode === "login" ? login(parsed.data) : signup(parsed.data))
        return INITIAL_STATE
      } catch (error) {
        const fieldErrors = error instanceof ApiError ? error.fieldErrors : {}
        const hasFieldErrors = Object.keys(fieldErrors).length > 0
        return { email: input.email, message: hasFieldErrors ? null : getErrorMessage(error), fieldErrors }
      }
    },
    INITIAL_STATE
  )

  const emailErrors = state.fieldErrors.email
  const passwordErrors = state.fieldErrors.password

  return (
    <form action={formAction} noValidate className="flex w-full max-w-sm flex-col gap-6">
      <div className="flex flex-col gap-1.5">
        <h1 className="text-2xl font-semibold tracking-tight">{copy.title}</h1>
        <p className="text-sm text-muted-foreground">{copy.description}</p>
      </div>

      {state.message ? (
        <Alert variant="destructive">
          <CircleAlert />
          <AlertTitle>{state.message}</AlertTitle>
        </Alert>
      ) : null}

      <FieldGroup>
        <Field data-invalid={emailErrors ? true : undefined}>
          <FieldLabel htmlFor="email">Email</FieldLabel>
          <Input
            id="email"
            name="email"
            type="email"
            autoComplete="email"
            placeholder="you@example.com"
            defaultValue={state.email}
            aria-invalid={emailErrors ? true : undefined}
            autoFocus
          />
          <FieldError errors={toFieldErrorItems(emailErrors)} />
        </Field>

        <Field data-invalid={passwordErrors ? true : undefined}>
          <FieldLabel htmlFor="password">Password</FieldLabel>
          <InputGroup>
            <InputGroupInput
              id="password"
              name="password"
              type={isPasswordVisible ? "text" : "password"}
              autoComplete={copy.passwordAutoComplete}
              aria-invalid={passwordErrors ? true : undefined}
            />
            <InputGroupAddon align="inline-end">
              <InputGroupButton
                size="icon-xs"
                aria-label={isPasswordVisible ? "Hide password" : "Show password"}
                aria-pressed={isPasswordVisible}
                onClick={() => {
                  setIsPasswordVisible((visible) => !visible)
                }}
              >
                {isPasswordVisible ? <EyeOff /> : <Eye />}
              </InputGroupButton>
            </InputGroupAddon>
          </InputGroup>
          {copy.passwordHint && !passwordErrors ? <FieldDescription>{copy.passwordHint}</FieldDescription> : null}
          <FieldError errors={toFieldErrorItems(passwordErrors)} />
        </Field>
      </FieldGroup>

      <Button type="submit" size="lg" disabled={isPending}>
        {isPending ? (
          <>
            <Spinner data-icon="inline-start" />
            {copy.submitting}
          </>
        ) : (
          copy.submit
        )}
      </Button>

      <p className="text-center text-sm text-muted-foreground">
        {copy.switchPrompt}{" "}
        <Link to={copy.switchTo} className="font-medium text-primary underline-offset-4 hover:underline">
          {copy.switchLabel}
        </Link>
      </p>
    </form>
  )
}
