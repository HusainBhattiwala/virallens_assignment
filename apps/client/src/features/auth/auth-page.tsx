function AuthForm({ mode }: AuthPageProps) {
  const config = AUTH_MODES[mode]
  const authenticate = useAuthStore((state) => state[mode])
  const [isPasswordVisible, setIsPasswordVisible] = useState(false)

  const [state, formAction, isPending] = useActionState(
    async (
      _previous: AuthFormState,
      formData: FormData
    ): Promise<AuthFormState> => {
      const input = {
        email: readField(formData, "email"),
        password: readField(formData, "password"),
      }
      const parsed = config.schema.safeParse(input)

      if (!parsed.success) {
        return {
          email: input.email,
          message: null,
          fieldErrors: z.flattenError(parsed.error).fieldErrors,
        }
      }

      try {
        await authenticate(parsed.data)
        return INITIAL_STATE
      } catch (error) {
        const fieldErrors = error instanceof ApiError ? error.fieldErrors : {}
        const hasFieldErrors = Object.keys(fieldErrors).length > 0
        return {
          email: input.email,
          message: hasFieldErrors ? null : getErrorMessage(error),
          fieldErrors,
        }
      }
    },
    INITIAL_STATE
  )

  const emailErrors = state.fieldErrors.email
  const passwordErrors = state.fieldErrors.password

  return (
    <form
      action={formAction}
      noValidate
      className="flex w-full max-w-sm flex-col gap-6"
    >
      <div className="flex flex-col gap-1.5">
        <h1 className="text-2xl font-semibold tracking-tight">
          {config.title}
        </h1>
        <p className="text-sm text-muted-foreground">{config.description}</p>
      </div>

      {state.message ? (
        <Alert variant="destructive">
          <CircleAlert />
          <AlertTitle>{state.message}</AlertTitle>
        </Alert>
      ) : null}

      <FieldGroup>
        <Field data-invalid={emailErrors ? true : undefined}>
          <FieldLabel htmlFor="email">Email</FieldLabel>
          <Input
            id="email"
            name="email"
            type="email"
            autoComplete="email"
            placeholder="you@example.com"
            defaultValue={state.email}
            aria-invalid={emailErrors ? true : undefined}
            autoFocus
          />
          <FieldError errors={toFieldErrorItems(emailErrors)} />
        </Field>

        <Field data-invalid={passwordErrors ? true : undefined}>
          <FieldLabel htmlFor="password">Password</FieldLabel>
          <InputGroup>
            <InputGroupInput
              id="password"
              name="password"
              type={isPasswordVisible ? "text" : "password"}
              autoComplete={config.passwordAutoComplete}
              aria-invalid={passwordErrors ? true : undefined}
            />
            <InputGroupAddon align="inline-end">
              <InputGroupButton
                size="icon-xs"
                aria-label={
                  isPasswordVisible ? "Hide password" : "Show password"
                }
                aria-pressed={isPasswordVisible}
                onClick={() => {
                  setIsPasswordVisible((visible) => !visible)
                }}
              >
                {isPasswordVisible ? <EyeOff /> : <Eye />}
              </InputGroupButton>
            </InputGroupAddon>
          </InputGroup>
          {config.passwordHint && !passwordErrors ? (
            <FieldDescription>{config.passwordHint}</FieldDescription>
          ) : null}
          <FieldError errors={toFieldErrorItems(passwordErrors)} />
        </Field>
      </FieldGroup>

      <Button type="submit" size="lg" disabled={isPending}>
        {isPending ? (
          <>
            <Spinner data-icon="inline-start" />
            {config.submitting}
          </>
        ) : (
          config.submit
        )}
      </Button>

      <p className="text-center text-sm text-muted-foreground">
        {config.switchPrompt}{" "}
        <Link
          to={config.switchTo}
          className="font-medium text-primary underline-offset-4 hover:underline"
        >
          {config.switchLabel}
        </Link>
      </p>
    </form>
  )
}
