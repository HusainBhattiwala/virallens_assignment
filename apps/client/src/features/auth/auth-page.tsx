import { CircleAlert, Eye, EyeOff } from "lucide-react"
import { useActionState, useState } from "react"
import { Link } from "react-router"
import { z } from "zod"
import { BrandMark } from "@/components/brand-mark"
import { ThemeToggle } from "@/components/theme-toggle"
import { Alert, AlertTitle } from "@/components/ui/alert"
import { Button } from "@/components/ui/button"
import {
  Field,
  FieldDescription,
  FieldError,
  FieldGroup,
  FieldLabel,
} from "@/components/ui/field"
import { Input } from "@/components/ui/input"
import {
  InputGroup,
  InputGroupAddon,
  InputGroupButton,
  InputGroupInput,
} from "@/components/ui/input-group"
import { Spinner } from "@/components/ui/spinner"
import { ApiError, type FieldErrors, getErrorMessage } from "@/lib/api"
import { loginSchema, signupSchema } from "./auth-schema"
import { useAuthStore } from "./auth-store"

type AuthMode = "login" | "signup"

const AUTH_MODES = {
  login: {
    schema: loginSchema,
    title: "Welcome back",
    description: "Log in to pick up your conversations.",
    submit: "Log in",
    submitting: "Logging in",
    switchPrompt: "New to Harbor?",
    switchLabel: "Create an account",
    switchTo: "/signup",
    passwordAutoComplete: "current-password",
    passwordHint: null,
  },
  signup: {
    schema: signupSchema,
    title: "Create your account",
    description: "Get help with orders, deliveries and returns.",
    submit: "Create account",
    submitting: "Creating account",
    switchPrompt: "Already have an account?",
    switchLabel: "Log in",
    switchTo: "/login",
    passwordAutoComplete: "new-password",
    passwordHint: "At least 8 characters.",
  },
} as const

interface AuthFormState {
  email: string
  message: string | null
  fieldErrors: FieldErrors
}

const INITIAL_STATE: AuthFormState = {
  email: "",
  message: null,
  fieldErrors: {},
}

const readField = (formData: FormData, name: string): string => {
  const value = formData.get(name)
  return typeof value === "string" ? value : ""
}

const toFieldErrorItems = (messages: string[] | undefined) =>
  messages?.map((message) => ({ message }))

interface AuthPageProps {
  mode: AuthMode
}

export function AuthPage({ mode }: AuthPageProps) {
  const config = AUTH_MODES[mode]

  return (
    <div className="flex min-h-svh flex-col bg-background">
      <header className="flex justify-end p-4">
        <ThemeToggle />
      </header>
      <main className="flex flex-1 items-center justify-center px-6 pb-16">
        <div className="flex w-full max-w-sm flex-col gap-8">
          <div className="flex flex-col items-center gap-5 text-center">
            <BrandMark className="size-11 rounded-xl" />
            <div className="flex flex-col gap-2">
              <h1 className="text-2xl font-semibold tracking-tight">
                {config.title}
              </h1>
              <p className="text-sm text-muted-foreground">
                {config.description}
              </p>
            </div>
          </div>
          <AuthForm key={mode} mode={mode} />
        </div>
      </main>
      <footer className="px-6 pb-6 text-center text-xs text-muted-foreground">
        Replies are generated by AI and can make mistakes.
      </footer>
    </div>
  )
}

function AuthForm({ mode }: AuthPageProps) {
  const config = AUTH_MODES[mode]
  const authenticate = useAuthStore((state) => state[mode])
  const [isPasswordVisible, setIsPasswordVisible] = useState(false)

  const [state, formAction, isPending] = useActionState(
    async (
      _previous: AuthFormState,
      formData: FormData
    ): Promise<AuthFormState> => {
      const input = {
        email: readField(formData, "email"),
        password: readField(formData, "password"),
      }
      const parsed = config.schema.safeParse(input)

      if (!parsed.success) {
        return {
          email: input.email,
          message: null,
          fieldErrors: z.flattenError(parsed.error).fieldErrors,
        }
      }

      try {
        await authenticate(parsed.data)
        return INITIAL_STATE
      } catch (error) {
        const fieldErrors = error instanceof ApiError ? error.fieldErrors : {}
        const hasFieldErrors = Object.keys(fieldErrors).length > 0
        return {
          email: input.email,
          message: hasFieldErrors ? null : getErrorMessage(error),
          fieldErrors,
        }
      }
    },
    INITIAL_STATE
  )

  const emailErrors = state.fieldErrors.email
  const passwordErrors = state.fieldErrors.password

  return (
    <form action={formAction} noValidate className="flex w-full flex-col gap-6">
      {state.message ? (
        <Alert variant="destructive">
          <CircleAlert />
          <AlertTitle>{state.message}</AlertTitle>
        </Alert>
      ) : null}

      <FieldGroup>
        <Field data-invalid={emailErrors ? true : undefined}>
          <FieldLabel htmlFor="email">Email</FieldLabel>
          <Input
            className="h-10 bg-card"
            id="email"
            name="email"
            type="email"
            autoComplete="email"
            placeholder="you@example.com"
            defaultValue={state.email}
            aria-invalid={emailErrors ? true : undefined}
            autoFocus
          />
          <FieldError errors={toFieldErrorItems(emailErrors)} />
        </Field>

        <Field data-invalid={passwordErrors ? true : undefined}>
          <FieldLabel htmlFor="password">Password</FieldLabel>
          <InputGroup className="h-10 bg-card">
            <InputGroupInput
              id="password"
              name="password"
              type={isPasswordVisible ? "text" : "password"}
              autoComplete={config.passwordAutoComplete}
              aria-invalid={passwordErrors ? true : undefined}
            />
            <InputGroupAddon align="inline-end">
              <InputGroupButton
                size="icon-xs"
                aria-label={
                  isPasswordVisible ? "Hide password" : "Show password"
                }
                aria-pressed={isPasswordVisible}
                onClick={() => {
                  setIsPasswordVisible((visible) => !visible)
                }}
              >
                {isPasswordVisible ? <EyeOff /> : <Eye />}
              </InputGroupButton>
            </InputGroupAddon>
          </InputGroup>
          {config.passwordHint && !passwordErrors ? (
            <FieldDescription>{config.passwordHint}</FieldDescription>
          ) : null}
          <FieldError errors={toFieldErrorItems(passwordErrors)} />
        </Field>
      </FieldGroup>

      <Button type="submit" size="lg" className="h-10" disabled={isPending}>
        {isPending ? (
          <>
            <Spinner data-icon="inline-start" />
            {config.submitting}
          </>
        ) : (
          config.submit
        )}
      </Button>

      <p className="text-center text-sm text-muted-foreground">
        {config.switchPrompt}{" "}
        <Link
          to={config.switchTo}
          className="font-medium text-primary underline-offset-4 hover:underline"
        >
          {config.switchLabel}
        </Link>
      </p>
    </form>
  )
}
